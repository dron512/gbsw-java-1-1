package ex02;

public class CharUni {
    static void main(String[] args) {
        char a = 'A';
        char a1 = 65;
        char a2 = '\u0041';

        System.out.println("a = "+a);
        System.out.println("a1 = "+a1);
        System.out.println("a2 = "+a2);

        System.out.println("a = "+ (int) a);

    }
}
